//! Built-in B-tree comparison membership from `PostgreSQL` 18.4 `pg_amop` and equality negators from `pg_operator`.

use super::BinaryOperatorCatalogEntry;

impl BinaryOperatorCatalogEntry {
    /// `(comparison, family)` interpretations of this exact selected operator.
    pub(crate) fn row_comparison_interpretations(self) -> impl Iterator<Item = (i64, i64)> {
        MEMBERS
            .iter()
            .filter_map(move |&(operator, family, comparison)| {
                (operator == self.oid).then_some((comparison, family))
            })
    }
}

