//! Explicit type tags belong to the native catalog image format, not Rust enum layout.

#[derive(Clone, Copy)]
#[repr(u8)]
pub(super) enum TypeTag {
    SmallInteger = 0,
    Integer = 1,
    BigInteger = 2,
    Oid = 3,
    Xid = 4,
    Boolean = 5,
    Void = 6,
    Text = 7,
    RefCursor = 8,
    Name = 9,
    Uuid = 10,
    Bpchar = 11,
    Real = 12,
    DoublePrecision = 13,
    Json = 14,
    Xml = 15,
    JsonB = 16,
    Bytea = 17,
    InternalChar = 18,
    Regproc = 19,
    Regprocedure = 20,
    Regclass = 21,
    Regnamespace = 22,
    Regcollation = 23,
    Regrole = 24,
    Regtype = 25,
    PgNodeTree = 26,
    AclItem = 27,
    Int2Vector = 28,
    OidVector = 29,
    AnyArray = 30,
    Record = 31,
    Date = 32,
    Time = 33,
    TimeTz = 34,
    Timestamp = 35,
    TimestampTz = 36,
    Interval = 37,
    Named = 38,
    Varchar = 39,
    Character = 40,
    Numeric = 41,
    Bit = 42,
    VarBit = 43,
    Array = 44,
    TimePrecision = 45,
    TimeTzPrecision = 46,
    TimestampPrecision = 47,
    TimestampTzPrecision = 48,
    IntervalWithFields = 49,
    Range = 50,
    Multirange = 51,
    DeclaredRange = 52,
    DeclaredMultirange = 53,
    Vector = 54,
    Tensor = 55,
    Domain = 56,
    Enum = 57,
    Composite = 58,
}
impl TypeTag {
    pub(super) fn decode(tag: u8) -> Result<Self, crate::SQLError> {
        Ok(match tag {
            0 => Self::SmallInteger,
            1 => Self::Integer,
            2 => Self::BigInteger,
            3 => Self::Oid,
            4 => Self::Xid,
            5 => Self::Boolean,
            6 => Self::Void,
            7 => Self::Text,
            8 => Self::RefCursor,
            9 => Self::Name,
            10 => Self::Uuid,
            11 => Self::Bpchar,
            12 => Self::Real,
            13 => Self::DoublePrecision,
            14 => Self::Json,
            15 => Self::Xml,
            16 => Self::JsonB,
            17 => Self::Bytea,
            18 => Self::InternalChar,
            19 => Self::Regproc,
            20 => Self::Regprocedure,
            21 => Self::Regclass,
            22 => Self::Regnamespace,
            23 => Self::Regcollation,
            24 => Self::Regrole,
            25 => Self::Regtype,
            26 => Self::PgNodeTree,
            27 => Self::AclItem,
            28 => Self::Int2Vector,
            29 => Self::OidVector,
            30 => Self::AnyArray,
            31 => Self::Record,
            32 => Self::Date,
            33 => Self::Time,
            34 => Self::TimeTz,
            35 => Self::Timestamp,
            36 => Self::TimestampTz,
            37 => Self::Interval,
            38 => Self::Named,
            39 => Self::Varchar,
            40 => Self::Character,
            41 => Self::Numeric,
            42 => Self::Bit,
            43 => Self::VarBit,
            44 => Self::Array,
            45 => Self::TimePrecision,
            46 => Self::TimeTzPrecision,
            47 => Self::TimestampPrecision,
            48 => Self::TimestampTzPrecision,
            49 => Self::IntervalWithFields,
            50 => Self::Range,
            51 => Self::Multirange,
            52 => Self::DeclaredRange,
            53 => Self::DeclaredMultirange,
            54 => Self::Vector,
            55 => Self::Tensor,
            56 => Self::Domain,
            57 => Self::Enum,
            58 => Self::Composite,
            _ => return Err(super::invalid("column type tag")),
        })
    }
}
