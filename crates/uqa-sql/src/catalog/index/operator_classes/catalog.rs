//! Built-in `pg_opclass` identities in `PostgreSQL` 18.4. B-tree selection and catalog projection read the same B-tree definitions.

use super::builtin_btree_operator_classes;

#[derive(Clone, Copy)]
pub struct BuiltinOperatorClass {
    pub oid: u32,
    pub method: u32,
    pub name: &'static str,
    pub family: u32,
    pub input: u32,
    pub default: bool,
    pub key: u32,
}

pub fn builtin_operator_classes() -> impl Iterator<Item = BuiltinOperatorClass> {
    builtin_btree_operator_classes()
        .iter()
        .map(|btree| {
            // B-tree name_ops stores keys as cstring. Other B-tree classes store their input type.
            let key = if btree.input_type_oid == 19 { 2275 } else { 0 };
            class(
                btree.oid,
                403,
                btree.name,
                btree.family_oid,
                btree.input_type_oid,
                btree.default,
                key,
            )
        })
        .chain(OTHER_CLASSES.iter().copied())
}

const fn class(
    oid: u32,
    method: u32,
    name: &'static str,
    family: u32,
    input: u32,
    default: bool,
    key: u32,
) -> BuiltinOperatorClass {
    BuiltinOperatorClass {
        oid,
        method,
        name,
        family,
        input,
        default,
        key,
    }
}

